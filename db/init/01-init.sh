#!/bin/sh
set -eu

: "${MYSQL_ROOT_PASSWORD:?MYSQL_ROOT_PASSWORD is required}"
: "${MYSQL_APP_USER:?MYSQL_APP_USER is required}"
: "${MYSQL_APP_PASSWORD:?MYSQL_APP_PASSWORD is required}"
: "${MYSQL_RELAY_USER:?MYSQL_RELAY_USER is required}"
: "${MYSQL_RELAY_PASSWORD:?MYSQL_RELAY_PASSWORD is required}"
: "${MYSQL_MIGRATOR_USER:?MYSQL_MIGRATOR_USER is required}"
: "${MYSQL_MIGRATOR_PASSWORD:?MYSQL_MIGRATOR_PASSWORD is required}"

unset MYSQL_HOST MYSQL_PORT MYSQL_UNIX_PORT
mysql --protocol=socket --socket=/var/run/mysqld/mysqld.sock -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS cors_admin
  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE IF NOT EXISTS cors_runtime
  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE USER IF NOT EXISTS '$MYSQL_APP_USER'@'%' IDENTIFIED BY '$MYSQL_APP_PASSWORD';
ALTER USER '$MYSQL_APP_USER'@'%' IDENTIFIED BY '$MYSQL_APP_PASSWORD';
GRANT SELECT, INSERT, UPDATE, DELETE ON cors_admin.* TO '$MYSQL_APP_USER'@'%';
GRANT SELECT ON cors_runtime.* TO '$MYSQL_APP_USER'@'%';

CREATE USER IF NOT EXISTS '$MYSQL_RELAY_USER'@'%' IDENTIFIED BY '$MYSQL_RELAY_PASSWORD';
ALTER USER '$MYSQL_RELAY_USER'@'%' IDENTIFIED BY '$MYSQL_RELAY_PASSWORD';
GRANT SELECT ON cors_admin.* TO '$MYSQL_RELAY_USER'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE ON cors_runtime.* TO '$MYSQL_RELAY_USER'@'%';

CREATE USER IF NOT EXISTS '$MYSQL_MIGRATOR_USER'@'%' IDENTIFIED BY '$MYSQL_MIGRATOR_PASSWORD';
ALTER USER '$MYSQL_MIGRATOR_USER'@'%' IDENTIFIED BY '$MYSQL_MIGRATOR_PASSWORD';
GRANT ALL PRIVILEGES ON cors_admin.* TO '$MYSQL_MIGRATOR_USER'@'%';
GRANT ALL PRIVILEGES ON cors_runtime.* TO '$MYSQL_MIGRATOR_USER'@'%';

FLUSH PRIVILEGES;
SQL
