CREATE TABLE IF NOT EXISTS relay_credentials (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(128) NOT NULL,
  username VARCHAR(128) NOT NULL,
  password_enc TEXT NOT NULL,
  owner_web_user_id BIGINT UNSIGNED NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_relay_credentials_owner (owner_web_user_id),
  KEY idx_relay_credentials_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS relay_jobs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  external_key VARCHAR(128) NULL,
  name VARCHAR(160) NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 0,
  upstream_host VARCHAR(190) NOT NULL,
  upstream_port INT NOT NULL DEFAULT 2101,
  upstream_mount VARCHAR(128) NOT NULL,
  upstream_credential_id BIGINT UNSIGNED NULL,
  upstream_proxy VARCHAR(255) NOT NULL DEFAULT '',
  upstream_ssl TINYINT(1) NOT NULL DEFAULT 0,
  upstream_ntrip_version ENUM('v1','v2') NOT NULL DEFAULT 'v2',
  downstream_host VARCHAR(190) NOT NULL,
  downstream_port INT NOT NULL DEFAULT 2101,
  downstream_mount VARCHAR(128) NOT NULL,
  downstream_credential_id BIGINT UNSIGNED NULL,
  downstream_proxy VARCHAR(255) NOT NULL DEFAULT '',
  downstream_ssl TINYINT(1) NOT NULL DEFAULT 0,
  downstream_ntrip_version ENUM('v1','v2') NOT NULL DEFAULT 'v2',
  downstream_mode ENUM('auto','post','source') NOT NULL DEFAULT 'auto',
  lat DECIMAL(10,7) NULL,
  lon DECIMAL(10,7) NULL,
  ua_prefix VARCHAR(100) NOT NULL DEFAULT '',
  nmea_interval_sec INT NOT NULL DEFAULT 0,
  origin ENUM('manual','import','discover') NOT NULL DEFAULT 'manual',
  origin_ref VARCHAR(190) NOT NULL DEFAULT '',
  tags JSON NULL,
  desired_revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
  upstream_key VARCHAR(255) NOT NULL,
  downstream_key VARCHAR(255) NOT NULL,
  owner_web_user_id BIGINT UNSIGNED NULL,
  created_by BIGINT UNSIGNED NULL,
  imported_at DATETIME(3) NULL,
  source_sha256 CHAR(64) NULL,
  deleted_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_relay_jobs_external_key (external_key),
  UNIQUE KEY uq_relay_jobs_endpoints (upstream_key, downstream_key),
  KEY idx_relay_jobs_owner (owner_web_user_id),
  KEY idx_relay_jobs_deleted (deleted_at),
  KEY idx_relay_jobs_origin (origin, origin_ref),
  KEY idx_relay_jobs_enabled (enabled),
  CONSTRAINT fk_relay_jobs_upstream_credential
    FOREIGN KEY (upstream_credential_id) REFERENCES relay_credentials(id) ON DELETE SET NULL,
  CONSTRAINT fk_relay_jobs_downstream_credential
    FOREIGN KEY (downstream_credential_id) REFERENCES relay_credentials(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
